"""Write docs/source/options.rst from the option table in options.py.

Run by conf.py on every docs build; can also be run by hand:
    python docs/source/generate_options.py
"""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))

from concordantmodes.options import PROFILES, option_reference  # noqa: E402

HEADER = """\
.. This file is generated by generate_options.py from concordantmodes/options.py.
   Edit the option table there, not this file.

Options reference
=================

Options are set in ``cma.toml`` (``name = value``, TOML syntax) or as keyword
arguments to ``Options(...)`` in a ``main.py``. Unknown names and invalid
values are reported before anything runs. ``cma options [name]`` prints this
list in the terminal.

"""


def _escape(text):
    return text.replace("*", "\\*").replace("|", "\\|")


def write_options_rst(path):
    lines = [HEADER]
    group = None
    for g, name, default, help_text in option_reference():
        if g != group:
            lines.append("\n{}\n{}\n\n".format(g, "-" * len(g)))
            group = g
        lines.append(
            "``{}``\n    Default: ``{}``. {}\n\n".format(
                name, default, _escape(help_text)
            )
        )

    lines.append("\nCluster profiles\n----------------\n\n")
    lines.append(
        "``cluster_profile`` applies a named group of settings before your own "
        "options, so anything you set yourself still wins.\n\n"
    )
    for name, prof in sorted(PROFILES.items()):
        settings = ", ".join(
            "``{} = {!r}``".format(k, v) for k, v in prof["options"].items()
        )
        lines.append(
            "``{}``\n    {} Sets {}.\n\n".format(name, prof["description"], settings)
        )

    lines.append(
        "\nOptions that currently have no effect\n"
        "-------------------------------------\n\n"
        "These are still accepted so older inputs keep running, but they do "
        "nothing; CMA prints a warning when one is set: "
    )
    hidden = [
        r[1]
        for r in option_reference(include_hidden=True)
        if r not in option_reference()
    ]
    lines.append(", ".join("``{}``".format(n) for n in hidden) + ".\n")

    with open(path, "w") as fh:
        fh.write("".join(lines))


if __name__ == "__main__":
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "options.rst")
    write_options_rst(out)
    print("wrote", out)
